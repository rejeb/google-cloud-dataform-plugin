package io.github.rejeb.dataform.language.lineage.toolwindow;

import com.intellij.openapi.project.DumbAware;
import com.intellij.openapi.project.Project;
import com.intellij.openapi.wm.ToolWindow;
import com.intellij.openapi.wm.ToolWindowFactory;
import org.jetbrains.annotations.NotNull;

/**
 * Creates the Dataform Lineage tool window. It has no stripe button until the Knowledge Catalog
 * source shows it for the first time, as the Run tool window before the first run.
 */
public final class LineageToolWindowFactory implements ToolWindowFactory, DumbAware {

    /**
     * Keeps the tool window out of the stripe until {@link LineageToolWindow#show} makes it available.
     */
    @Override
    public boolean shouldBeAvailable(@NotNull Project project) {
        return false;
    }

    @Override
    public void createToolWindowContent(@NotNull Project project, @NotNull ToolWindow toolWindow) {
        if (LineageToolWindow.getInstance(project) instanceof LineageToolWindowImpl window) {
            window.createContents(toolWindow);
        }
    }
}
